package com.example.service.integrations.ytmusic

import android.content.Context
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.security.MessageDigest

/**
 * Manages YouTube Music accounts, session persistence, and InnerTube authentication headers.
 * Implements SimpMusic-compatible multi-account support with account switching,
 * automated identity resolution via getAccountSwitcherEndpoint, and on-device yt-dlp cookie export.
 */
class YtAccountManager private constructor(private val context: Context) {

    companion object {
        private const val TAG = "YtAccountManager"
        private const val PREFS_NAME = "anyfy_yt_accounts"
        private const val KEY_ACCOUNTS_JSON = "accounts_json"
        private const val KEY_ACTIVE_ACCOUNT_ID = "active_account_id"
        private const val COOKIE_FILE_NAME = "ytdlp-cookie.txt"

        @Volatile
        private var instance: YtAccountManager? = null

        fun getInstance(context: Context): YtAccountManager {
            return instance ?: synchronized(this) {
                instance ?: YtAccountManager(context.applicationContext).also { instance = it }
            }
        }

        /**
         * Calculates the standard SAPISIDHASH for YouTube InnerTube authenticated requests.
         */
        fun calculateSapisidHash(sapisid: String, origin: String = "https://music.youtube.com"): String {
            return try {
                val timestamp = System.currentTimeMillis() / 1000L
                val input = "$timestamp $sapisid $origin"
                val md = MessageDigest.getInstance("SHA-1")
                val digest = md.digest(input.toByteArray(Charsets.UTF_8))
                val hex = digest.joinToString("") { "%02x".format(it) }
                "SAPISIDHASH ${timestamp}_$hex"
            } catch (e: Exception) {
                Log.w(TAG, "Failed to compute SAPISIDHASH: ${e.message}")
                ""
            }
        }

        /**
         * Converts standard cookie string into Netscape HTTP Cookie File format for yt-dlp.
         */
        fun toNetscapeCookieFormat(cookieString: String): String {
            val sb = StringBuilder()
            sb.append("# Netscape HTTP Cookie File\n")
            sb.append("# Generated by Anyfy (SimpMusic Engine)\n\n")

            val pairs = cookieString.split(";").map { it.trim() }.filter { it.contains("=") }
            val expiry = (System.currentTimeMillis() / 1000L) + (365 * 24 * 3600L)

            for (pair in pairs) {
                val idx = pair.indexOf("=")
                if (idx > 0) {
                    val key = pair.substring(0, idx).trim()
                    val value = pair.substring(idx + 1).trim()
                    // Domain, include subdomains, path, secure, expiration, name, value
                    sb.append(".youtube.com\tTRUE\t/\tTRUE\t$expiry\t$key\t$value\n")
                    sb.append(".google.com\tTRUE\t/\tTRUE\t$expiry\t$key\t$value\n")
                }
            }
            return sb.toString()
        }
    }

    private val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)

    private val _accounts = MutableStateFlow<List<YtAccount>>(emptyList())
    val accounts: StateFlow<List<YtAccount>> = _accounts.asStateFlow()

    private val _activeAccount = MutableStateFlow<YtAccount?>(null)
    val activeAccount: StateFlow<YtAccount?> = _activeAccount.asStateFlow()

    init {
        loadAccounts()
    }

    @Synchronized
    private fun loadAccounts() {
        try {
            val jsonStr = prefs.getString(KEY_ACCOUNTS_JSON, null)
            val activeId = prefs.getString(KEY_ACTIVE_ACCOUNT_ID, null)

            val list = mutableListOf<YtAccount>()
            if (!jsonStr.isNullOrBlank()) {
                val jsonArr = JSONArray(jsonStr)
                for (i in 0 until jsonArr.length()) {
                    val obj = jsonArr.getJSONObject(i)
                    val id = obj.optString("id")
                    val name = obj.optString("name")
                    val email = obj.optString("email")
                    val avatarUrl = obj.optString("avatarUrl")
                    val cookie = obj.optString("cookie")
                    val pageId = if (obj.has("pageId") && !obj.isNull("pageId")) obj.optString("pageId").ifBlank { null } else null
                    val authUser = obj.optInt("authUser", 0)
                    val addedAt = obj.optLong("addedAt", System.currentTimeMillis())
                    val isActive = (id == activeId)
                    list.add(
                        YtAccount(
                            id = id,
                            name = name,
                            email = email,
                            avatarUrl = avatarUrl,
                            cookie = cookie,
                            pageId = pageId,
                            authUser = authUser,
                            isActive = isActive,
                            addedAt = addedAt
                        )
                    )
                }
            }

            _accounts.value = list
            val resolvedActive = list.firstOrNull { it.id == activeId } ?: list.firstOrNull()
            _activeAccount.value = resolvedActive
            if (resolvedActive != null) {
                writeCookieFile(resolvedActive.cookie)
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error loading accounts: ${e.message}")
            _accounts.value = emptyList()
            _activeAccount.value = null
        }
    }

    /**
     * Authenticates and resolves real YouTube Music account details using InnerTube endpoints.
     * Equivalent to SimpMusic's SettingsViewModel.addAccount(cookie).
     */
    suspend fun addAccountFromCookie(cookie: String): Result<YtAccount> = withContext(Dispatchers.IO) {
        val cleanCookie = cookie.trim()
        if (cleanCookie.isBlank()) {
            return@withContext Result.failure(IllegalArgumentException("Cookie cannot be empty"))
        }

        try {
            // Compute authentication headers
            val sapisidMatch = Regex("""(?:^|;\s*)(?:__Secure-3PAPISID|SAPISID)=([^;]+)""").find(cleanCookie)
            val sapisid = sapisidMatch?.groupValues?.get(1) ?: ""
            val authHeader = if (sapisid.isNotBlank()) calculateSapisidHash(sapisid) else ""

            val headers = mutableMapOf(
                "Cookie" to cleanCookie,
                "Origin" to "https://music.youtube.com",
                "x-origin" to "https://music.youtube.com"
            )
            if (authHeader.isNotBlank()) {
                headers["Authorization"] = authHeader
            }

            val client = YtMusicClient(authHeaderProvider = { headers })

            // 1. Primary: getAccountSwitcherEndpoint
            var accountList = emptyList<YtAccount>()
            try {
                val switcherRaw = client.getAccountSwitcherEndpoint(cleanCookie, headers)
                accountList = YtMusicParser.parseAccountSwitcherResponse(switcherRaw, cleanCookie)
            } catch (e: Exception) {
                Log.w(TAG, "getAccountSwitcherEndpoint call failed: ${e.message}")
            }

            // 2. Secondary fallback: account/account_menu
            if (accountList.isEmpty()) {
                try {
                    val menuJson = client.getAccountMenu(headers)
                    YtMusicParser.parseAccountMenuResponse(menuJson, cleanCookie)?.let {
                        accountList = listOf(it)
                    }
                } catch (e: Exception) {
                    Log.w(TAG, "account_menu call failed: ${e.message}")
                }
            }

            // 3. Last fallback: If valid SAPISID exists, accept session with fallback name
            if (accountList.isEmpty() && sapisid.isNotBlank()) {
                accountList = listOf(
                    YtAccount(
                        id = "yt_user_${System.currentTimeMillis()}",
                        name = "YouTube Music Account",
                        email = "Active Session",
                        avatarUrl = "",
                        cookie = cleanCookie,
                        pageId = null,
                        authUser = 0,
                        isActive = true
                    )
                )
            }

            if (accountList.isEmpty()) {
                return@withContext Result.failure(IllegalStateException("No valid YouTube account found for this cookie"))
            }

            val primary = accountList.first()
            val saved = addOrUpdateAccount(primary)
            writeCookieFile(cleanCookie)
            Result.success(saved)
        } catch (e: Exception) {
            Log.e(TAG, "addAccountFromCookie failed: ${e.message}", e)
            Result.failure(e)
        }
    }

    @Synchronized
    fun addOrUpdateAccount(account: YtAccount): YtAccount {
        val current = _accounts.value.toMutableList()
        val existingIdx = current.indexOfFirst { it.id == account.id || (it.email.isNotBlank() && it.email == account.email) }
        val updated = if (existingIdx >= 0) {
            val existing = current[existingIdx]
            val merged = account.copy(
                id = existing.id,
                name = account.name.ifBlank { existing.name },
                email = account.email.ifBlank { existing.email },
                avatarUrl = account.avatarUrl.ifBlank { existing.avatarUrl },
                cookie = account.cookie.ifBlank { existing.cookie },
                pageId = account.pageId ?: existing.pageId,
                authUser = if (account.authUser != 0) account.authUser else existing.authUser,
                isActive = true
            )
            current[existingIdx] = merged
            merged
        } else {
            val newAcc = account.copy(isActive = true)
            current.add(newAcc)
            newAcc
        }

        val mapped = current.map { it.copy(isActive = it.id == updated.id) }
        _accounts.value = mapped
        _activeAccount.value = updated
        persistAccounts(mapped, updated.id)
        writeCookieFile(updated.cookie)
        return updated
    }

    @Synchronized
    fun switchAccount(accountId: String): Boolean {
        val current = _accounts.value
        val target = current.firstOrNull { it.id == accountId } ?: return false
        val mapped = current.map { it.copy(isActive = it.id == target.id) }
        _accounts.value = mapped
        _activeAccount.value = target.copy(isActive = true)
        persistAccounts(mapped, target.id)
        writeCookieFile(target.cookie)
        return true
    }

    @Synchronized
    fun removeAccount(accountId: String): Boolean {
        val current = _accounts.value.toMutableList()
        val removed = current.removeAll { it.id == accountId }
        if (!removed) return false

        val nextActive = current.firstOrNull()
        val mapped = current.map { it.copy(isActive = it.id == nextActive?.id) }
        _accounts.value = mapped
        _activeAccount.value = nextActive?.copy(isActive = true)
        persistAccounts(mapped, nextActive?.id)
        if (nextActive != null) {
            writeCookieFile(nextActive.cookie)
        } else {
            clearCookieFile()
        }
        return true
    }

    @Synchronized
    fun clearAccounts() {
        _accounts.value = emptyList()
        _activeAccount.value = null
        prefs.edit().clear().apply()
        clearCookieFile()
    }

    /**
     * Resolves complete authentication headers for YouTube Music InnerTube requests.
     * Incorporates SAPISIDHASH, X-Goog-Authuser, X-Goog-Pageid, and origin headers.
     */
    fun getAuthHeaders(): Map<String, String> {
        val active = _activeAccount.value ?: return emptyMap()
        val cookie = active.cookie.trim()
        if (cookie.isBlank()) return emptyMap()

        val headers = mutableMapOf<String, String>()
        headers["Cookie"] = cookie
        headers["Origin"] = "https://music.youtube.com"
        headers["x-origin"] = "https://music.youtube.com"
        headers["Referer"] = "https://music.youtube.com/"
        headers["X-Goog-Authuser"] = active.authUser.toString()

        active.pageId?.let { pageId ->
            if (pageId.isNotBlank()) {
                headers["X-Goog-Pageid"] = pageId
            }
        }

        // Extract SAPISID or __Secure-3PAPISID
        val sapisidMatch = Regex("""(?:^|;\s*)(?:__Secure-3PAPISID|SAPISID)=([^;]+)""").find(cookie)
        if (sapisidMatch != null) {
            val sapisid = sapisidMatch.groupValues[1]
            val hash = calculateSapisidHash(sapisid)
            if (hash.isNotBlank()) {
                headers["Authorization"] = hash
            }
        }
        return headers
    }

    /**
     * Returns the cookie file for on-device yt-dlp execution.
     */
    fun getCookieFile(): File? {
        val file = File(context.filesDir, COOKIE_FILE_NAME)
        return if (file.exists() && file.length() > 0) file else null
    }

    private fun writeCookieFile(cookieString: String) {
        try {
            val file = File(context.filesDir, COOKIE_FILE_NAME)
            val netscape = toNetscapeCookieFormat(cookieString)
            file.writeText(netscape, Charsets.UTF_8)
            Log.d(TAG, "Saved yt-dlp cookie file to ${file.absolutePath} (${file.length()} bytes)")
        } catch (e: Exception) {
            Log.w(TAG, "Failed to write cookie file: ${e.message}")
        }
    }

    private fun clearCookieFile() {
        try {
            val file = File(context.filesDir, COOKIE_FILE_NAME)
            if (file.exists()) file.delete()
        } catch (_: Exception) {}
    }

    private fun persistAccounts(list: List<YtAccount>, activeId: String?) {
        try {
            val jsonArr = JSONArray()
            for (acc in list) {
                val obj = JSONObject().apply {
                    put("id", acc.id)
                    put("name", acc.name)
                    put("email", acc.email)
                    put("avatarUrl", acc.avatarUrl)
                    put("cookie", acc.cookie)
                    acc.pageId?.let { put("pageId", it) }
                    put("authUser", acc.authUser)
                    put("addedAt", acc.addedAt)
                }
                jsonArr.put(obj)
            }
            prefs.edit()
                .putString(KEY_ACCOUNTS_JSON, jsonArr.toString())
                .putString(KEY_ACTIVE_ACCOUNT_ID, activeId)
                .apply()
        } catch (e: Exception) {
            Log.e(TAG, "Failed to persist accounts: ${e.message}")
        }
    }
}
